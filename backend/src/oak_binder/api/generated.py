"""Generated-paper intake (spec 3C, 8.8; Pass 2 Stage D, D31): a module delivers a complete
paper with its inputs and citations; the Binder checks it, files it as a draft and records
where it came from."""

from __future__ import annotations

import hmac
import uuid

from fastapi import APIRouter, HTTPException, Request, status

from oak_binder.api.deps import CurrentUser, DbSession, Now, Spine, WorkMind
from oak_binder.api.papers import paper_out
from oak_binder.config import Settings
from oak_binder.errors import Forbidden, NotFound
from oak_binder.models.generation import locked_fields_for
from oak_binder.schemas.generated import GeneratedPaperIn, GenerationOut
from oak_binder.schemas.papers import PaperOut
from oak_binder.services import access, binders, generated, papers, spine_papers

router = APIRouter(tags=["generated papers"])


def intake_gate(request: Request, user: str) -> None:
    """Who may deliver papers (decisions 8 and 12). When OAK_INTAKE_CREDENTIAL is set the
    module presents it as a bearer; under OAK_AUTH=header the identity must be one of
    OAK_INTAKE_IDENTITIES, and none configured means no intake at all."""
    settings: Settings = request.app.state.settings
    if settings.intake_credential:
        presented = request.headers.get("Authorization", "").encode("utf-8")
        expected = f"Bearer {settings.intake_credential}".encode()
        if not hmac.compare_digest(presented, expected):
            raise HTTPException(
                status.HTTP_401_UNAUTHORIZED,
                "the intake credential is missing or wrong (OAK_INTAKE_CREDENTIAL)",
                headers={"WWW-Authenticate": "Bearer"},
            )
    if settings.auth == "header":
        allowed = settings.intake_identity_set()
        if not allowed:
            raise Forbidden(
                "no intake identities are configured (OAK_INTAKE_IDENTITIES), so no module "
                "may deliver papers (D31)"
            )
        if user not in allowed:
            raise Forbidden(
                f"{user!r} is not an authorised intake identity (OAK_INTAKE_IDENTITIES; D31)"
            )


@router.post("/api/binders/{binder_id}/generated-papers", status_code=status.HTTP_201_CREATED)
def receive(
    binder_id: uuid.UUID,
    body: GeneratedPaperIn,
    request: Request,
    session: DbSession,
    user: CurrentUser,
    now: Now,
    spine: Spine,
    workmind: WorkMind,
) -> PaperOut:
    intake_gate(request, user)
    binder = binders.get_binder(session, binder_id)
    settings: Settings = request.app.state.settings
    paper = generated.receive(
        session,
        binder,
        body,
        user=user,
        now=now,
        max_bytes=settings.max_provenance_bytes,
        workmind=workmind,
    )
    return paper_out(session, paper.id, spine)


@router.get("/api/papers/{paper_id}/generation")
def generation(
    paper_id: uuid.UUID, request: Request, session: DbSession, now: Now, spine: Spine
) -> GenerationOut:
    paper = papers.get_paper(session, paper_id)
    binder = papers.binder_of(session, paper)
    access.record(
        session, binder, access.reader(request, binder), f"generation of {paper.ref}", now
    )
    row = papers.latest_generation(session, paper)
    if row is None:
        raise NotFound(f"paper {paper.ref} was not generated by a module")
    return GenerationOut.build(
        row, locked_fields_for(row.source), spine_papers.paper_freshness(spine, binder, row)
    )
