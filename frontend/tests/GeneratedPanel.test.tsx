import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, expect, test, vi } from "vitest";

import type { Generation } from "../src/api";
import { BinderPage } from "../src/pages/BinderPage";
import { PaperPage } from "../src/pages/PaperPage";
import { SPINE_PAPERS_NONE, SPINE_UNCONFIGURED, binderFixture, mockApi, paperFixture } from "./mockApi";

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
});

const LOCKED = ["title", "section", "sa_refs", "objective", "procedure", "population_sample", "result"];

const sampling: Generation = {
  id: "g1",
  source: "sampling",
  module: "oak_sampling",
  module_version: "example",
  run_id: "sampling-run-example-001",
  generated_at: "2026-10-31T10:15:00+05:30",
  received_by: "sampling@oak",
  received_at: "2026-10-31T10:16:02Z",
  content_hash_at_intake: "a".repeat(64),
  spine_figures_check: null,
  run_verification: null,
  locked_fields: LOCKED,
  freshness: null,
  payload: {
    inputs: { population_value: "9800000.00", sample_size: 60 },
    citations: [{ source: "sales_register_fy26.xlsx", rows: "2-1285" }],
    sampling: { formula: "interval = population_value / sample_size", seed: 20261031 },
  },
};

test("a generated sampling paper shows its provenance, formula and seed, and locks the module's fields", async () => {
  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({
      ref: "D-3",
      title: "Revenue: sample of sales invoices",
      population_sample: "Formula: interval = population_value / sample_size. Seed: 20261031.",
      conclusion: "",
      generated: sampling,
      generated_by: "sampling",
    }),
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: /D-3/ });
  const panel = screen.getByTestId("generated-panel");
  expect(within(panel).getByRole("heading", { name: "Generated by Sampling" })).toBeInTheDocument();
  expect(within(panel).getByTestId("gen-module")).toHaveTextContent("oak_sampling example");
  expect(within(panel).getByTestId("gen-formula")).toHaveTextContent("interval = population_value / sample_size");
  expect(within(panel).getByTestId("gen-seed")).toHaveTextContent("20261031");
  expect(panel).toHaveTextContent("sampling-run-example-001");
  expect(panel).toHaveTextContent("sampling@oak");
  // Decision 10: on a draft, the sequence is stated: attach after intake, review both, then prepare.
  expect(within(panel).getByTestId("gen-sequence")).toHaveTextContent(
    "Supporting attachments are uploaded separately, after intake and before preparation.",
  );
  // Inputs and citations are there, as delivered, behind a toggle.
  expect(screen.queryByTestId("gen-raw")).not.toBeInTheDocument();
  fireEvent.click(within(panel).getByRole("button", { name: "Show inputs and citations" }));
  expect(screen.getByTestId("gen-raw")).toHaveTextContent("sales_register_fy26.xlsx");
  expect(screen.getByTestId("gen-raw")).toHaveTextContent('"sample_size": 60');
  // The module's fields are locked in the form; the conclusion is a person's to write.
  expect(screen.getByTestId("locked-note")).toHaveTextContent("Only the conclusion can be written here");
  for (const label of ["Title", "Section", "SA references (comma separated)", "Objective", "Procedure performed", "Population and sample", "Result"]) {
    expect(screen.getByLabelText(label, { exact: false })).toBeDisabled();
  }
  expect(screen.getByLabelText("Conclusion")).toBeEnabled();
});

test("a materiality memo says whether its Spine figures were verified against the linked version", async () => {
  const memo: Generation = {
    ...sampling,
    id: "g2",
    source: "materiality",
    module: "oak_materiality",
    run_id: null,
    spine_figures_check: "verified",
    run_verification: null,
    payload: {
      inputs: { benchmark_head_id: "PL.R.1" },
      citations: [{ source: "Financial Spine", head_id: "PL.R.1" }],
      materiality: {
        benchmark: { head_id: "PL.R.1", amount: "9800000.00" },
        band: { overall: "490000.00", performance: "250000.00" },
        spine_figures: { version_id: "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", figures: { "PL.R.1": "9800000.00" } },
      },
    },
  };
  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({ ref: "C-1", title: "Materiality memo", generated: memo, generated_by: "materiality" }),
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Materiality" });
  expect(screen.getByTestId("gen-spine-check")).toHaveTextContent("aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa");
  expect(screen.getByTestId("gen-spine-check")).toHaveTextContent("verified against the linked version");
  expect(screen.getByTestId("generated-panel")).toHaveTextContent("no run id given");
  expect(screen.getByTestId("generated-panel")).toHaveTextContent('"performance": "250000.00"');
  cleanup();

  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({
      ref: "C-1",
      generated: { ...memo, spine_figures_check: "not_checked" },
      generated_by: "materiality",
    }),
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Materiality" });
  expect(screen.getByTestId("gen-spine-check")).toHaveTextContent("not checked: the binder is not linked");
});

test("once prepared, the panel no longer tells the preparer to attach files first", async () => {
  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({
      status: "prepared",
      current_version: 1,
      generated: sampling,
      generated_by: "sampling",
    }),
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Sampling" });
  expect(screen.queryByTestId("gen-sequence")).not.toBeInTheDocument();
});

test("a hand-made paper shows no generated panel and every field stays editable", async () => {
  mockApi({ "GET /api/papers/p1/review-notes": [], "GET /api/papers/p1": paperFixture() });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: /D-1/ });
  expect(screen.queryByTestId("generated-panel")).not.toBeInTheDocument();
  expect(screen.queryByTestId("locked-note")).not.toBeInTheDocument();
  expect(screen.getByLabelText("Result")).toBeEnabled();
});

test("the binder index marks generated papers with their source", async () => {
  const binder = binderFixture();
  binder.sections[2]!.papers[0]!.generated_by = "materiality";
  mockApi({
    "GET /api/binders/b1": binder,
    "GET /api/binders/b1/discussions": [],
    "GET /api/binders/b1/departures": [],
    "GET /api/binders/b1/spine-papers": SPINE_PAPERS_NONE, "GET /api/binders/b1/spine": SPINE_UNCONFIGURED,
  });
  render(<BinderPage id="b1" />);
  await screen.findByRole("heading", { name: "Index" });
  const marks = screen.getAllByTestId("generated-mark");
  expect(marks).toHaveLength(1);
  expect(marks[0]).toHaveTextContent("generated · Materiality");
  expect(marks[0]!.closest("a")).toHaveTextContent("C-1 Materiality memo");
});
