const lead = paperFixture({
  ref: "D-L",
  title: "Lead schedule: Financial statement area D",
  objective: null,
  procedure: null,
  conclusion: null,
  generated: spine,
  generated_by: "spine",
});

test("a current Spine paper shows the version it came from, the shape of what was served, and no banner", async () => {
  mockApi({ "GET /api/papers/p1/review-notes": [], "GET /api/papers/p1": lead });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Financial Spine" });
  expect(screen.getByTestId("gen-spine-version")).toHaveTextContent(`Final ${V} locked 2026-10-20T10:00:00+05:30`);
  expect(screen.getByTestId("gen-spine-kind")).toHaveTextContent("lead schedule for area D");
  expect(screen.getByTestId("gen-spine-counts")).toHaveTextContent("1 financial statement line(s), 2 ledger row(s), 0 head(s) with no ledger entry, 1 adjustment(s)");
  expect(screen.getByTestId("gen-freshness")).toHaveTextContent("current");
  expect(screen.queryByRole("button", { name: /Regenerate/ })).not.toBeInTheDocument();
  // The Spine's fields are locked; objective and procedure stay a person's.
  expect(screen.getByLabelText("Result", { exact: false })).toBeDisabled();
  expect(screen.getByLabelText("Objective")).toBeEnabled();
  expect(screen.getByLabelText("Procedure performed")).toBeEnabled();
});

test("a stale Spine paper on an open binder offers Regenerate and shows what happened to the references", async () => {
  const stale: Generation = {
    ...spine,
    freshness: {
      state: "stale",
      detail: "built from Spine version 'Final' (aaaa); the binder is now linked to 'Post-lock work' (bbbb)",
      recorded_version_id: V,
      recorded_version_label: "Final",
    },
  };
  const regenerated = {
    ...paperFixture({ ref: "D-L", generated: { ...spine, run_id: "b1/bbbb/eeee/D" }, generated_by: "spine" }),
    regeneration: {
      references: { added: ["BS.A.2"], removed: ["BS.A.1"], kept: [], for_review: ["BS.L.1"] },
      previous_run_id: spine.run_id,
      run_id: "b1/bbbb/eeee/D",
    },
  };
  let reloads = 0;
  const calls = mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": () => (reloads++ > 0 ? regenerated : paperFixture({ ref: "D-L", generated: stale, generated_by: "spine" })),
    "POST /api/papers/p1/regenerate": regenerated,
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Financial Spine" });
  const banner = screen.getByTestId("gen-freshness");
  expect(banner).toHaveTextContent("Stale: built from Spine version 'Final'");
  expect(banner).toHaveTextContent("now linked to 'Post-lock work'");
  fireEvent.click(within(banner).getByRole("button", { name: "Regenerate from the linked version" }));
  const changes = await screen.findByTestId("gen-regeneration");
  expect(changes).toHaveTextContent("added: BS.A.2");
  expect(changes).toHaveTextContent("removed (Binder-written, target no longer served): BS.A.1");
  expect(changes).toHaveTextContent("kept: none");
  expect(changes).toHaveTextContent("for your review (not written by the Binder; target no longer served): BS.L.1");
  await waitFor(() => expect(calls.filter((c) => c.method === "POST")).toHaveLength(1));
  expect(calls.filter((c) => c.method === "POST")[0]?.path).toBe("/api/papers/p1/regenerate");
});

test("a stale Spine paper on an assembled binder states the staleness without a button", async () => {
  const stale: Generation = {
    ...spine,
    freshness: { state: "stale", detail: "built from Spine version 'Final' (aaaa); the binder is now linked to 'B' (bbbb)", recorded_version_id: V, recorded_version_label: "Final" },
  };
  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({ ref: "D-L", status: "signed_off", current_version: 3, binder_state: "assembled", generated: stale, generated_by: "spine" }),
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Financial Spine" });
  expect(screen.getByTestId("gen-freshness")).toHaveTextContent("Stale:");
  expect(screen.getByTestId("gen-no-regenerate")).toHaveTextContent("never a blocker");
  expect(screen.queryByRole("button", { name: /Regenerate/ })).not.toBeInTheDocument();
});

test("a not-checked Spine paper says why, and a refused regeneration is shown as said", async () => {
  const unchecked: Generation = {
    ...spine,
    freshness: { state: "not_checked", detail: "freshness not checked: the Financial Spine could not answer", recorded_version_id: V, recorded_version_label: "Final" },
  };
  mockApi({
    "GET /api/papers/p1/review-notes": [],
    "GET /api/papers/p1": paperFixture({ ref: "D-L", generated: unchecked, generated_by: "spine" }),
    "POST /api/papers/p1/regenerate": { httpStatus: 422, body: { detail: "cannot regenerate: the Financial Spine could not answer" } },
  });
  render(<PaperPage id="p1" />);
  await screen.findByRole("heading", { name: "Generated by Financial Spine" });
  expect(screen.getByTestId("gen-freshness")).toHaveTextContent("Not checked: freshness not checked: the Financial Spine could not answer");
  fireEvent.click(screen.getByRole("button", { name: "Regenerate from the linked version" }));
  expect(await screen.findByRole("alert")).toHaveTextContent("could not answer");
});

