      ledgers: [{ head_id: "BS.A.1", ledger_key: "hdfc", ledger_name: "HDFC", adjusted: "1250000.00" }, { head_id: "BS.A.1", ledger_key: "cash", ledger_name: "Cash", adjusted: "0.00" }],
